/**
 * Detect hardiness zone from postal/ZIP code
 */
export function detectZoneFromPostalCode(postalCode: string): number | null {
  if (!postalCode || typeof postalCode !== 'string') {
    return null;
  }

  const cleaned = postalCode.replace(/\s+/g, '').toUpperCase();

  // Check if it's a Canadian postal code (starts with letter)
  if (/^[A-Z]/.test(cleaned)) {
    const firstLetter = cleaned[0];
    return canadianPostalToZone[firstLetter] || null;
  }

  // US ZIP code - check first 3 digits
  if (/^\d{5}/.test(cleaned)) {
    const zipPrefix = cleaned.substring(0, 3);
    return zipToZone[zipPrefix] || null;
  }

  return null;
}

/**
 * Validate zone number
 */
export function isValidZone(zone: number): boolean {
  return Number.isInteger(zone) && zone >= 1 && zone <= 13;
}

